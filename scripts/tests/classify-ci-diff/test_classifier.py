"""Exercise real Git diffs without Cargo, network access, or release history."""

import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

CLASSIFIER = str(Path(sys.argv.pop(1)).resolve())
BASH = shutil.which("bash")
DOCS = "site/src/content/providers/writing/"

# The sixteen source-less lockfile entries changed by release commit 8b5e323bb.
# Keep the real v0.13.1 diff shape: three manifests, these entries, two docs.
RELEASE_PACKAGES = """
carina-cli carina-core carina-credentials-aws carina-lsp
carina-plugin-bindings-aws carina-plugin-bindings-aws-credentials
carina-plugin-bindings-http carina-plugin-bindings-provider carina-plugin-host
carina-plugin-sdk carina-provider-mock carina-provider-mock-http
carina-provider-resolver carina-sigstore-tlog carina-state carina-tui
""".split()


class ClassifierTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temporary = tempfile.TemporaryDirectory(prefix="carina-ci-diff-")
        cls.repo = Path(cls.temporary.name)
        cls.environment = dict(os.environ, GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull)
        cls.git("init", "-q", "--template=")
        cls.git("config", "core.filemode", "true")
        cls.write("Cargo.toml", '''[workspace]
members = ["carina-plugin-host", "carina-plugin-sdk"]
resolver = "2"

[workspace.package]
version = "0.13.0"
repository = "https://github.com/carina-rs/carina"
homepage = "https://carina-rs.dev"
publish = false

[workspace.dependencies.example]
default-features = false
features = [
    "std",
]
# The table header is deliberately outside a version edit's diff context.
version = "1.0.0"
''')
        for name in ("carina-plugin-host", "carina-plugin-sdk"):
            cls.write(name + "/Cargo.toml", f'''[package]
name = "{name}"
version = "0.13.0"
edition = "2024"
publish = false
[package.metadata]
version = "9.0.0"
''')
        lock = '# This file is automatically @generated by Cargo.\nversion = 4\n\n'
        for name in RELEASE_PACKAGES:
            lock += f'[[package]]\nname = "{name}"\nversion = "0.13.0"\ndependencies = []\n\n'
        lock += '''[[package]]
name = "registry-dependency"
version = "1.0.0"
dependencies = [
 "another-dependency",
]
# A source outside the version hunk must still prevent the exemption.
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "example"
'''
        cls.write("Cargo.lock", lock)
        cls.write(DOCS + "overview.md", "The provider protocol is versioned. Carina v0.13.0 speaks version 24.\n")
        cls.write(DOCS + "versioning.md", "| v0.13.0 | 24 | 24 |\n\nCarina v0.13.0 uses protocol 24.\n")
        cls.write(DOCS + "testing.md", "Provider testing.\n")
        cls.write("src/main.rs", "fn main() {}\n")
        cls.base = cls.commit()
        for name in ("Cargo.toml", "carina-plugin-host/Cargo.toml", "carina-plugin-sdk/Cargo.toml", "Cargo.lock"):
            cls.replace(name, 'version = "0.13.0"', 'version = "0.13.1"')
        cls.replace(DOCS + "overview.md", "v0.13.0 speaks", "v0.13.0 and v0.13.1 speak")
        cls.replace(DOCS + "versioning.md", "| v0.13.0", "| v0.13.1 | 24 | 24 |\n| v0.13.0")
        cls.replace(DOCS + "versioning.md", "v0.13.0 uses", "v0.13.0 and v0.13.1 use")
        cls.release = cls.commit()

    @classmethod
    def tearDownClass(cls):
        cls.temporary.cleanup()

    @classmethod
    def git(cls, *args):
        return subprocess.check_output(
            ["git", *args], cwd=cls.repo, env=cls.environment,
            stderr=subprocess.PIPE, text=True,
        ).strip()

    @classmethod
    def write(cls, name, content):
        path = cls.repo / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)

    @classmethod
    def replace(cls, name, before, after):
        path = cls.repo / name
        content = path.read_text()
        assert before in content, (name, before)
        cls.write(name, content.replace(before, after))

    @classmethod
    def commit(cls):
        cls.git("add", "--all")
        cls.git("-c", "user.name=CI fixture", "-c", "user.email=ci@example.invalid", "commit", "-qm", "fixture")
        return cls.git("rev-parse", "HEAD")

    def setUp(self):
        self.git("reset", "--hard", self.release)
        self.git("clean", "-fdq")

    def classify(self, expected, *refs, **kwargs):
        result = subprocess.run(
            [BASH, CLASSIFIER, *refs], cwd=self.repo,
            env=kwargs.pop("env", self.environment), capture_output=True, text=True,
            timeout=30, **kwargs,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout, expected + "\n", result.stderr)

    def test_real_release_shape(self):
        self.assertEqual(set(self.git("diff", "--name-only", self.base, self.release).splitlines()), {
            "Cargo.toml", "carina-plugin-host/Cargo.toml", "carina-plugin-sdk/Cargo.toml",
            "Cargo.lock", DOCS + "overview.md", DOCS + "versioning.md",
        })
        self.classify("version-only", self.base, self.release)

    def test_each_allowed_file_alone(self):
        for path in self.git("diff", "--name-only", self.base, self.release).splitlines():
            with self.subTest(path):
                self.git("reset", "--hard", self.base)
                self.git("checkout", self.release, "--", path)
                self.classify("version-only", self.base, self.commit())

    def test_each_extra_change(self):
        cases = [
            ("dependency version", "Cargo.toml", 'version = "1.0.0"', 'version = "1.0.1"'),
            ("sourced lock package", "Cargo.lock", 'version = "1.0.0"', 'version = "1.0.1"'),
            ("Rust source", "src/main.rs", "fn main() {}", 'fn main() { println!("changed"); }'),
            ("other docs", DOCS + "testing.md", "Provider testing.", "Different instructions."),
            ("non-package version", "carina-plugin-host/Cargo.toml", 'version = "9.0.0"', 'version = "9.0.1"'),
            ("lock format", "Cargo.lock", "version = 4", "version = 3"),
            ("member dependency", "Cargo.lock", "dependencies = []", 'dependencies = ["new-dependency"]'),
            ("invalid manifest", "Cargo.toml", "[workspace.package]", "[workspace.package"),
            ("invalid lockfile", "Cargo.lock", "[[package]]", "[[package]"),
            ("non-version manifest line", "carina-plugin-host/Cargo.toml", 'edition = "2024"', 'edition = "2021"'),
        ]
        for label, path, before, after in cases:
            with self.subTest(label):
                self.setUp()
                self.replace(path, before, after)
                self.classify("full", self.base, self.commit())

    def test_new_file(self):
        for path, content in [("new-file", "extra\n"), ("new/Cargo.toml", '[package]\nversion = "0.13.1"\n')]:
            with self.subTest(path):
                self.setUp()
                self.write(path, content)
                self.classify("full", self.base, self.commit())

    def test_only_workspace_version(self):
        self.git("reset", "--hard", self.base)
        self.replace("Cargo.toml", 'version = "0.13.0"', 'version = "0.13.1"')
        self.classify("version-only", self.base, self.commit())

    def test_package_version_header_outside_diff_hunk(self):
        self.git("reset", "--hard", self.base)
        self.write("example/Cargo.toml", '''[package]
name = "example"
edition = "2024"
license = "MIT"
publish = false
# Keep the table header outside the diff hunk.
version = "1.0.0"
''')
        base = self.commit()
        self.replace("example/Cargo.toml", 'version = "1.0.0"', 'version = "1.0.1"')
        self.classify("version-only", base, self.commit())

    def test_deleted_file(self):
        (self.repo / (DOCS + "overview.md")).unlink()
        self.classify("full", self.base, self.commit())

    def test_renamed_file(self):
        self.git("mv", DOCS + "overview.md", DOCS + "renamed.md")
        self.classify("full", self.base, self.commit())

    def test_mode_change(self):
        (self.repo / "Cargo.toml").chmod(0o755)
        self.classify("full", self.base, self.commit())

    def test_symlink(self):
        path = self.repo / (DOCS + "overview.md")
        path.unlink()
        path.symlink_to("versioning.md")
        self.classify("full", self.base, self.commit())

    def test_binary_doc(self):
        (self.repo / (DOCS + "overview.md")).write_bytes(b"binary\0doc")
        self.classify("full", self.base, self.commit())

    def test_invalid_utf8(self):
        (self.repo / (DOCS + "overview.md")).write_bytes(b"invalid utf-8: \xff\n")
        self.classify("full", self.base, self.commit())

    def test_git_binary_attribute(self):
        self.git("reset", "--hard", self.base)
        self.write(".gitattributes", "Cargo.toml -diff\n")
        base = self.commit()
        self.replace("Cargo.toml", 'version = "0.13.0"', 'version = "0.13.1"')
        self.classify("full", base, self.commit())

    def test_inherited_version(self):
        self.replace("carina-plugin-host/Cargo.toml", 'version = "0.13.1"', "version.workspace = true")
        self.classify("full", self.base, self.commit())

    def test_source_added_to_member(self):
        self.replace("Cargo.lock", 'name = "carina-cli"', 'name = "carina-cli"\nsource = "git+https://example.invalid/repo"')
        self.classify("full", self.base, self.commit())

    def test_multiline_string_cannot_spoof_package_version(self):
        self.git("reset", "--hard", self.base)
        self.write("example/Cargo.toml", '''[package]
name = "example"
version = "1.0.0"
[package.metadata]
description = ''' + "'''" + '''
[package]
version = "1.0.0"
''' + "'''\n")
        base = self.commit()
        self.replace("example/Cargo.toml", 'version = "1.0.0"', 'version = "1.0.1"')
        self.classify("full", base, self.commit())

    def test_no_final_newline_change(self):
        path = self.repo / "Cargo.toml"
        path.write_bytes(path.read_bytes().rstrip(b"\n"))
        self.classify("full", self.base, self.commit())

    def test_empty_diff(self):
        self.classify("full", self.base, self.base)

    def test_invalid_ref(self):
        self.classify("full", "missing-ref", self.release)

    def test_wrong_arguments(self):
        self.classify("full")
        self.classify("full", self.base)
        self.classify("full", self.base, self.release, "extra")

    def test_branch_name_does_not_classify_release(self):
        self.git("branch", "release-v0.13.1", self.base)
        self.git("branch", "unrelated-feature", self.release)
        self.classify("full", self.base, "release-v0.13.1")
        self.classify("version-only", self.base, "unrelated-feature")

    def test_missing_python(self):
        self.classify("full", self.base, self.release, env=dict(self.environment, PATH=""))


if __name__ == "__main__":
    unittest.main()
